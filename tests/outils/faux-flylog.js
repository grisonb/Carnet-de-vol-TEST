const csv = v => (/[",\n]/.test(v) ? `"${String(v).replace(/"/g, '""')}"` : String(v));

// lignes : objets partiels { DATE: ..., ... } ; les colonnes absentes sont vides (FEU… = 0)
export function fauxFlyLog(lignes) {
  const out = [ENTETES.join(',')];
  for (const l of lignes) {
    const c = { FEU: '0', LARGAGES_CDB_DASH: '0', LARGAGES_INSTRUCTION_CDB_DASH: '0', ...l };
    if (!c.ROUTE) c.ROUTE = `${c.DEPARTURE_AIRPORT || ''}|${c.ARRIVAL_AIRPORT || ''}`;
    out.push(ENTETES.map(h => csv(c[h] ?? '')).join(','));
  }
  return out.join('\n') + '\n';
}

